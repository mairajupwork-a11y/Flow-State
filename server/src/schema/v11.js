/**
 * v11: tools for software houses.
 *  - time_entries: timers and logged time per work item (timesheets, billable hours)
 *  - integrations: GitHub / GitLab webhooks and chat channels (Slack, Teams, Discord, Google Chat)
 *  - dev_links: commits, pull/merge requests and branches linked to work items
 *  - audit_log: who changed what in a workspace (security reviews)
 *  - two-factor sign-in on users; a client name on projects; read-only client share links
 */
const TABLES = ['time_entries', 'integrations', 'dev_links', 'audit_log', 'share_links'];

function render(pg) {
  const id = pg ? 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY';
  const now = pg ? "to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')" : "(datetime('now'))";
  const ine = pg ? ' IF NOT EXISTS' : '';
  const addCol = (table, col) => (pg ? `ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${col};` : `ALTER TABLE ${table} ADD COLUMN ${col};`);
  return `
  CREATE TABLE${ine} time_entries (
    ${id},
    workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    started_at TEXT NOT NULL,
    ended_at TEXT,
    minutes INTEGER,
    note TEXT NOT NULL DEFAULT '',
    billable INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS time_entries_user ON time_entries (user_id, started_at);
  CREATE INDEX IF NOT EXISTS time_entries_issue ON time_entries (issue_id);
  CREATE INDEX IF NOT EXISTS time_entries_ws ON time_entries (workspace_id, started_at);
  CREATE TABLE${ine} integrations (
    ${id},
    workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    secret TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL DEFAULT '',
    settings TEXT NOT NULL DEFAULT '{}',
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT ${now},
    last_event_at TEXT,
    last_status TEXT NOT NULL DEFAULT ''
  );
  CREATE INDEX IF NOT EXISTS integrations_ws ON integrations (workspace_id);
  CREATE TABLE${ine} dev_links (
    ${id},
    issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    provider TEXT NOT NULL,
    kind TEXT NOT NULL,
    ext_id TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL DEFAULT '',
    state TEXT NOT NULL DEFAULT '',
    author TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT ${now},
    updated_at TEXT NOT NULL DEFAULT ${now},
    UNIQUE (issue_id, provider, kind, ext_id)
  );
  CREATE TABLE${ine} audit_log (
    ${id},
    workspace_id INTEGER REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL DEFAULT '',
    detail TEXT NOT NULL DEFAULT '',
    ip TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS audit_log_ws ON audit_log (workspace_id, id);
  CREATE TABLE${ine} share_links (
    ${id},
    project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    token TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL DEFAULT '',
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT ${now},
    revoked_at TEXT
  );
  ${addCol('users', "totp_secret TEXT NOT NULL DEFAULT ''")}
  ${addCol('users', 'totp_enabled INTEGER NOT NULL DEFAULT 0')}
  ${addCol('users', "totp_recovery TEXT NOT NULL DEFAULT '[]'")}
  ${addCol('projects', "client TEXT NOT NULL DEFAULT ''")}
  ${pg ? lockDown() : ''}`;
}

const lockDown = () => `DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[${TABLES.map((t) => `'${t}'`).join(',')}]
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN EXECUTE format('REVOKE ALL ON TABLE %I FROM anon', t); END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN EXECUTE format('REVOKE ALL ON TABLE %I FROM authenticated', t); END IF;
  END LOOP;
END $$;`;

export const v11Sqlite = () => render(false);
export const v11Postgres = () => render(true);
