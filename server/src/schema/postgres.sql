-- Flowstate schema for PostgreSQL (Supabase or any Postgres 13+).
-- Applied automatically by the server on first start (see db-postgres.js),
-- or paste it into the Supabase SQL editor. Safe to re-run.
--
-- Timestamps are stored as UTC text ("YYYY-MM-DD HH24:MI:SS") and dates as
-- "YYYY-MM-DD", matching the SQLite build, so both share one code path.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  color TEXT NOT NULL,
  job_title TEXT NOT NULL DEFAULT '',
  locale TEXT NOT NULL DEFAULT 'en-GB',
  theme TEXT NOT NULL DEFAULT 'light',
  session_version INTEGER NOT NULL DEFAULT 0,
  email_verified INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email ON users (lower(email));

CREATE TABLE IF NOT EXISTS workspaces (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  region TEXT NOT NULL DEFAULT 'uk',
  locale TEXT NOT NULL DEFAULT 'en-GB',
  week_start INTEGER NOT NULL DEFAULT 1,
  team_size TEXT NOT NULL DEFAULT '',
  use_case TEXT NOT NULL DEFAULT '',
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS memberships (
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('admin','member','viewer')),
  joined_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (workspace_id, user_id)
);

CREATE TABLE IF NOT EXISTS invites (
  token TEXT PRIMARY KEY,
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','member','viewer')),
  invited_by INTEGER NOT NULL REFERENCES users(id),
  designation TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  accepted_at TEXT
);

CREATE TABLE IF NOT EXISTS projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  color TEXT NOT NULL,
  template TEXT NOT NULL,
  methodology TEXT NOT NULL DEFAULT 'scrum',
  settings TEXT NOT NULL DEFAULT '{}',
  lead_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  issue_seq INTEGER NOT NULL DEFAULT 100,
  archived INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (workspace_id, key)
);

CREATE TABLE IF NOT EXISTS statuses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('todo','progress','done')),
  color TEXT NOT NULL,
  position INTEGER NOT NULL,
  wip_limit INTEGER
);
CREATE INDEX IF NOT EXISTS statuses_project ON statuses(project_id, position);

CREATE TABLE IF NOT EXISTS sprints (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  goal TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL DEFAULT 'planned' CHECK (state IN ('planned','active','closed')),
  start_date TEXT,
  end_date TEXT,
  completed_at TEXT,
  committed_points INTEGER,
  completed_points INTEGER,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS sprints_project ON sprints(project_id);

CREATE TABLE IF NOT EXISTS phases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  position INTEGER NOT NULL,
  state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','active','review','complete')),
  gate TEXT NOT NULL DEFAULT '',
  decision TEXT NOT NULL DEFAULT '',
  start_date TEXT,
  end_date TEXT,
  started_at TEXT,
  completed_at TEXT,
  approved_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS phases_project ON phases(project_id, position);

CREATE TABLE IF NOT EXISTS issues (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  number INTEGER NOT NULL,
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status_id INTEGER NOT NULL REFERENCES statuses(id),
  priority TEXT NOT NULL DEFAULT 'medium' CHECK (priority IN ('urgent','high','medium','low')),
  assignee_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reporter_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sprint_id INTEGER REFERENCES sprints(id) ON DELETE SET NULL,
  phase_id INTEGER REFERENCES phases(id) ON DELETE SET NULL,
  epic_id INTEGER REFERENCES issues(id) ON DELETE SET NULL,
  parent_id INTEGER REFERENCES issues(id) ON DELETE CASCADE,
  story_points INTEGER,
  start_date TEXT,
  due_date TEXT,
  labels TEXT NOT NULL DEFAULT '[]',
  rank DOUBLE PRECISION NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  resolved_at TEXT,
  UNIQUE (project_id, number)
);
CREATE INDEX IF NOT EXISTS issues_project ON issues(project_id, status_id, rank);
CREATE INDEX IF NOT EXISTS issues_assignee ON issues(assignee_id);
CREATE INDEX IF NOT EXISTS issues_sprint ON issues(sprint_id);
CREATE INDEX IF NOT EXISTS issues_phase ON issues(phase_id);
CREATE INDEX IF NOT EXISTS issues_parent ON issues(parent_id);
CREATE INDEX IF NOT EXISTS issues_epic ON issues(epic_id);

CREATE TABLE IF NOT EXISTS checklist_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0,
  position INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS checklist_issue ON checklist_items(issue_id);

CREATE TABLE IF NOT EXISTS comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  author_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  body TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  edited_at TEXT
);
CREATE INDEX IF NOT EXISTS comments_issue ON comments(issue_id);

CREATE TABLE IF NOT EXISTS issue_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  target_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('blocks','relates','duplicates')),
  UNIQUE (source_id, target_id, kind)
);

CREATE TABLE IF NOT EXISTS watchers (
  issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (issue_id, user_id)
);

CREATE TABLE IF NOT EXISTS activity (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  project_id INTEGER REFERENCES projects(id) ON DELETE CASCADE,
  issue_id INTEGER REFERENCES issues(id) ON DELETE CASCADE,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  verb TEXT NOT NULL,
  data TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS activity_issue ON activity(issue_id, id);
CREATE INDEX IF NOT EXISTS activity_ws ON activity(workspace_id, id);
CREATE INDEX IF NOT EXISTS activity_project ON activity(project_id, id);

CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  issue_id INTEGER REFERENCES issues(id) ON DELETE CASCADE,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  kind TEXT NOT NULL,
  text TEXT NOT NULL,
  read INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id, workspace_id, id);

CREATE TABLE IF NOT EXISTS todos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  done INTEGER NOT NULL DEFAULT 0,
  important INTEGER NOT NULL DEFAULT 0,
  day TEXT NOT NULL,
  time_block TEXT NOT NULL DEFAULT 'anytime' CHECK (time_block IN ('morning','afternoon','evening','anytime')),
  issue_id INTEGER REFERENCES issues(id) ON DELETE SET NULL,
  position DOUBLE PRECISION NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  completed_at TEXT
);
CREATE INDEX IF NOT EXISTS todos_user_day ON todos(user_id, day);

CREATE TABLE IF NOT EXISTS entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  status TEXT NOT NULL,
  owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  data TEXT NOT NULL DEFAULT '{}',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS entries_project ON entries(project_id, kind);

CREATE TABLE IF NOT EXISTS measurements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  value DOUBLE PRECISION NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS measurements_project ON measurements(project_id, day);

-- Hot lookups and foreign keys used in WHERE / ON DELETE.
CREATE INDEX IF NOT EXISTS issues_status_rank ON issues (status_id, rank);
CREATE INDEX IF NOT EXISTS notifications_issue ON notifications (issue_id);
CREATE INDEX IF NOT EXISTS todos_issue ON todos (issue_id);
CREATE INDEX IF NOT EXISTS issue_links_target ON issue_links (target_id);
CREATE INDEX IF NOT EXISTS invites_workspace ON invites (workspace_id);
CREATE INDEX IF NOT EXISTS memberships_user ON memberships (user_id);
CREATE INDEX IF NOT EXISTS users_email_exact ON users (email);

-- Supabase publishes the public schema through its REST API to the browser
-- "anon" and "authenticated" roles. Flowstate talks to the database only from
-- its own server, so lock those roles out: row level security with no
-- policies denies them everything, and their table privileges are revoked.
-- The server's own connection (the table owner) is unaffected.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','workspaces','memberships','invites','projects','statuses','sprints','phases','issues',
    'checklist_items','comments','issue_links','watchers','activity','notifications','todos','entries','measurements']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON TABLE %I FROM anon', t);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
      EXECUTE format('REVOKE ALL ON TABLE %I FROM authenticated', t);
    END IF;
  END LOOP;
END $$;
