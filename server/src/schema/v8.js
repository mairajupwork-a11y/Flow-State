/**
 * v8: password resets, file attachments, custom fields, automations, push
 * subscriptions, notification preferences and private calendar feeds.
 * One definition renders to both dialects.
 */
const TABLES = ['app_kv', 'password_resets', 'attachments', 'custom_fields', 'issue_field_values', 'automations', 'automation_runs', 'push_subscriptions'];

function render(pg) {
  const id = pg ? 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY';
  const now = pg ? "to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')" : "(datetime('now'))";
  const blob = pg ? 'BYTEA' : 'BLOB';
  const ine = pg ? ' IF NOT EXISTS' : '';
  return `
  CREATE TABLE${ine} app_kv (key TEXT PRIMARY KEY, value TEXT NOT NULL);
  CREATE TABLE${ine} password_resets (
    ${id},
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TEXT NOT NULL,
    used_at TEXT,
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS password_resets_user ON password_resets (user_id);
  CREATE TABLE${ine} attachments (
    ${id},
    issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    mime TEXT NOT NULL,
    size INTEGER NOT NULL,
    data ${blob} NOT NULL,
    uploader_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS attachments_issue ON attachments (issue_id);
  CREATE TABLE${ine} custom_fields (
    ${id},
    project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    options TEXT NOT NULL DEFAULT '[]',
    position INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS custom_fields_project ON custom_fields (project_id, position);
  CREATE TABLE${ine} issue_field_values (
    issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    field_id INTEGER NOT NULL REFERENCES custom_fields(id) ON DELETE CASCADE,
    value TEXT NOT NULL,
    PRIMARY KEY (issue_id, field_id)
  );
  CREATE INDEX IF NOT EXISTS issue_field_values_field ON issue_field_values (field_id);
  CREATE TABLE${ine} automations (
    ${id},
    project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    when_json TEXT NOT NULL,
    then_json TEXT NOT NULL,
    enabled INTEGER NOT NULL DEFAULT 1,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    run_count INTEGER NOT NULL DEFAULT 0,
    last_run_at TEXT,
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS automations_project ON automations (project_id);
  CREATE TABLE${ine} automation_runs (
    automation_id INTEGER NOT NULL REFERENCES automations(id) ON DELETE CASCADE,
    issue_id INTEGER NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    ran_at TEXT NOT NULL DEFAULT ${now},
    PRIMARY KEY (automation_id, issue_id)
  );
  CREATE INDEX IF NOT EXISTS automation_runs_issue ON automation_runs (issue_id);
  CREATE TABLE${ine} push_subscriptions (
    ${id},
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    user_agent TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT ${now}
  );
  CREATE INDEX IF NOT EXISTS push_subscriptions_user ON push_subscriptions (user_id);
  ALTER TABLE users ADD COLUMN${ine} notify_email TEXT NOT NULL DEFAULT 'important';
  ALTER TABLE users ADD COLUMN${ine} notify_push TEXT NOT NULL DEFAULT 'important';
  ALTER TABLE users ADD COLUMN${ine} calendar_token TEXT;
  CREATE UNIQUE INDEX IF NOT EXISTS users_calendar_token ON users (calendar_token);
  ${pg ? lockDown() : ''}`;
}

/** Same Supabase lock-down as schema/postgres.sql, for the new tables. */
const lockDown = () => `DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[${TABLES.map((t) => `'${t}'`).join(',')}]
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN EXECUTE format('REVOKE ALL ON TABLE %I FROM anon', t); END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN EXECUTE format('REVOKE ALL ON TABLE %I FROM authenticated', t); END IF;
  END LOOP;
END $$;`;

export const v8Sqlite = () => render(false);
export const v8Postgres = () => render(true);
export const V8_TABLES = TABLES;
